import { createHash } from "node:crypto";
import { formatUnits6, METHOD_LABEL, summarize, type StatementInput } from "./statement";

/// ISO 20022 camt.053.001.08 (BankToCustomerStatement) for a merchant's Veriga
/// account. Settled sales are booked credit entries (BOOK) in USD-pegged QUSDC.
/// Advance repayments routed to the pool are booked debit entries. Customer-
/// attested cash sales moved no funds on-chain, so they appear as information-only
/// entries (status INFO) with zero booked effect. Accounting tools still see the
/// activity, and nothing inflates the balance.
///
/// Currency is reported as USD because QUSDC is a USD stablecoin; each entry
/// carries its on-chain transaction hash as the end-to-end reference.

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

function isoDate(d: Date): string {
  return d.toISOString().slice(0, 10);
}

function isoDateTime(d: Date): string {
  return d.toISOString().replace(/\.\d{3}Z$/, "Z");
}

export function buildCamt053(input: StatementInput): string {
  const generatedAt = input.generatedAt ?? new Date();
  const lines = [...input.lines].sort((a, b) => a.timestamp.getTime() - b.timestamp.getTime());
  const sum = summarize(lines);
  const msgId = createHash("sha256")
    .update(`${input.merchantWallet}|${input.from.toISOString()}|${input.to.toISOString()}|${sum.count}`)
    .digest("hex")
    .slice(0, 32)
    .toUpperCase();
  const acctName = input.qieName ?? input.merchantName;
  const closing = sum.netSettledReceived;

  const entries: string[] = [];
  for (const l of lines) {
    const settled = l.tier === 0;
    const amt = formatUnits6(l.amount);
    const info = settled
      ? `Veriga sale #${l.receiptId} paid in ${METHOD_LABEL[l.method] ?? "QUSDC"}`
      : `Veriga customer-attested cash sale #${l.receiptId} (no on-chain funds movement)`;
    entries.push(`      <Ntry>
        <NtryRef>${esc(l.receiptId)}</NtryRef>
        <Amt Ccy="USD">${amt}</Amt>
        <CdtDbtInd>CRDT</CdtDbtInd>
        <Sts><Cd>${settled ? "BOOK" : "INFO"}</Cd></Sts>
        <BookgDt><DtTm>${isoDateTime(l.timestamp)}</DtTm></BookgDt>
        <ValDt><Dt>${isoDate(l.timestamp)}</Dt></ValDt>
        <AcctSvcrRef>${esc(l.txHash)}</AcctSvcrRef>
        <BkTxCd><Prtry><Cd>${settled ? "VERIGA-SETTLED" : "VERIGA-ATTESTED"}</Cd><Issr>Veriga</Issr></Prtry></BkTxCd>
        <NtryDtls><TxDtls>
          <Refs><EndToEndId>${esc(l.invoiceRef.slice(0, 35))}</EndToEndId><TxId>${esc(l.txHash.slice(0, 35))}</TxId></Refs>
          <RltdPties><Dbtr><Pty><Nm>${esc(l.payer)}</Nm></Pty></Dbtr></RltdPties>
          <AddtlTxInf>${esc(info)}</AddtlTxInf>
        </TxDtls></NtryDtls>
      </Ntry>`);
    if (settled && BigInt(l.repaidToPool) > 0n) {
      entries.push(`      <Ntry>
        <NtryRef>${esc(l.receiptId)}-R</NtryRef>
        <Amt Ccy="USD">${formatUnits6(l.repaidToPool)}</Amt>
        <CdtDbtInd>DBIT</CdtDbtInd>
        <Sts><Cd>BOOK</Cd></Sts>
        <BookgDt><DtTm>${isoDateTime(l.timestamp)}</DtTm></BookgDt>
        <ValDt><Dt>${isoDate(l.timestamp)}</Dt></ValDt>
        <AcctSvcrRef>${esc(l.txHash)}</AcctSvcrRef>
        <BkTxCd><Prtry><Cd>VERIGA-ADVANCE-REPAY</Cd><Issr>Veriga</Issr></Prtry></BkTxCd>
        <AddtlNtryInf>Automatic working-capital advance repayment from sale #${esc(l.receiptId)}</AddtlNtryInf>
      </Ntry>`);
    }
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<Document xmlns="urn:iso:std:iso:20022:tech:xsd:camt.053.001.08">
  <BkToCstmrStmt>
    <GrpHdr>
      <MsgId>${msgId}</MsgId>
      <CreDtTm>${isoDateTime(generatedAt)}</CreDtTm>
      <AddtlInf>Generated by Veriga from QIE mainnet (chain 1990). Every entry is verifiable on-chain by its transaction hash.</AddtlInf>
    </GrpHdr>
    <Stmt>
      <Id>${msgId.slice(0, 16)}</Id>
      <CreDtTm>${isoDateTime(generatedAt)}</CreDtTm>
      <FrToDt><FrDtTm>${isoDateTime(input.from)}</FrDtTm><ToDtTm>${isoDateTime(input.to)}</ToDtTm></FrToDt>
      <Acct>
        <Id><Othr><Id>${esc(input.merchantWallet)}</Id><SchmeNm><Prtry>QIE-EVM-ADDRESS</Prtry></SchmeNm></Othr></Id>
        <Ccy>USD</Ccy>
        <Nm>${esc(acctName)}</Nm>
        <Svcr><FinInstnId><Nm>Veriga on QIE</Nm></FinInstnId></Svcr>
      </Acct>
      <Bal>
        <Tp><CdOrPrtry><Cd>OPBD</Cd></CdOrPrtry></Tp>
        <Amt Ccy="USD">0.00</Amt>
        <CdtDbtInd>CRDT</CdtDbtInd>
        <Dt><Dt>${isoDate(input.from)}</Dt></Dt>
      </Bal>
      <Bal>
        <Tp><CdOrPrtry><Cd>CLBD</Cd></CdOrPrtry></Tp>
        <Amt Ccy="USD">${formatUnits6(closing < 0n ? -closing : closing)}</Amt>
        <CdtDbtInd>${closing < 0n ? "DBIT" : "CRDT"}</CdtDbtInd>
        <Dt><Dt>${isoDate(input.to)}</Dt></Dt>
      </Bal>
      <TxsSummry>
        <TtlNtries><NbOfNtries>${entries.length}</NbOfNtries></TtlNtries>
        <TtlCdtNtries><NbOfNtries>${sum.count}</NbOfNtries><Sum>${formatUnits6(sum.settled + sum.attested)}</Sum></TtlCdtNtries>
        <TtlDbtNtries><NbOfNtries>${entries.length - sum.count}</NbOfNtries><Sum>${formatUnits6(sum.repaidToPool)}</Sum></TtlDbtNtries>
      </TxsSummry>
${entries.join("\n")}
      <AddtlStmtInf>Settled: ${formatUnits6(sum.settled)} USD. Customer-attested (info only): ${formatUnits6(sum.attested)} USD. Distinct customers: ${sum.customers}.</AddtlStmtInf>
    </Stmt>
  </BkToCstmrStmt>
</Document>
`;
}
