// Writes prisma/schema.sqlite.prisma from the Postgres schema, for tests and
// local development without a Postgres server.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../prisma");
const src = fs.readFileSync(path.join(dir, "schema.prisma"), "utf8").replace(/\r\n/g, "\n");
const out = src
  .replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"')
  .replace(/url\s*=\s*env\("POSTGRES_PRISMA_URL"\)/, 'url = env("DATABASE_URL")')
  .replace(/^\s*directUrl\s*=.*\n/m, "")
  .replace(/^\s*\/\/.*\n/gm, "");
fs.writeFileSync(path.join(dir, "schema.sqlite.prisma"), "// Generated by scripts/sqlite-schema.mjs. Edit schema.prisma instead.\n" + out);
console.log("wrote prisma/schema.sqlite.prisma");
