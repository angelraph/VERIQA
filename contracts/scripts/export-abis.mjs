// Writes compiled ABIs into packages/shared/src/abi as typed `as const` arrays,
// so viem infers event/function types in the indexer and web app.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifacts = path.resolve(here, "../artifacts/contracts");
const out = path.resolve(here, "../../packages/shared/src/abi");
const targets = {
  MerchantRegistry: "merchantRegistry",
  PaymentReceipts: "paymentReceipts",
  TrustScoreOracle: "trustScoreOracle",
  WorkingCapitalPool: "workingCapitalPool",
  VerigaForwarder: "verigaForwarder",
};
for (const [contract, name] of Object.entries(targets)) {
  const file = path.join(artifacts, `${contract}.sol`, `${contract}.json`);
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  const body = `// Generated by contracts/scripts/export-abis.mjs. Do not edit by hand.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(out, `${name}.ts`), body);
  console.log(`wrote ${name}.ts (${abi.length} entries)`);
}
